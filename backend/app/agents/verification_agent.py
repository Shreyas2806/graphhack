"""
app/agents/verification_agent.py — Verification Agent for GraphMind.

Responsibilities
----------------
1. Accept user's original question, answer generated by Reasoning Agent,
   retrieved supporting facts, and source text / fact identifiers.
2. Verify evidence integrity: ensure cited fact IDs exist in retrieved evidence
   and in FalkorDB (not fabricated).
3. Verify source traceability: retain original source text for every cited fact.
4. Verify claim support: check whether the answer's factual claims are supported
   by the retrieved evidence.
5. Contradiction detection: identify conflicting facts in evidence or against FalkorDB.
6. Staleness / Versioning: verify that superseded or stale facts are not treated
   as current truth without explicit qualification.
7. Insufficient evidence: mark unsupported claims as unsupported rather than inventing evidence.
8. Failure handling: if a dependency fails, report an error / indeterminate result
   rather than falsely labeling an unchecked answer as verified.
"""

from __future__ import annotations

import json
import logging
import re
from typing import Any, Optional

from pydantic import BaseModel, Field

# Module-level imports enable test patching via mock.patch at these names.
from app.llm import generate_text
from app.graph import _get_graph

logger = logging.getLogger(__name__)

# ── Status Constants ──────────────────────────────────────────────────────────
STATUS_SUPPORTED = "SUPPORTED"
STATUS_PARTIALLY_SUPPORTED = "PARTIALLY_SUPPORTED"
STATUS_UNSUPPORTED = "UNSUPPORTED"
STATUS_CONFLICTING = "CONFLICTING"
STATUS_ERROR = "ERROR"

# ── Gemini Prompt Template ────────────────────────────────────────────────────
_VERIFICATION_PROMPT = """\
You are a strict factual verification agent.

Given the Answer and the Evidence below, evaluate the factual claims
and determine whether each claim is strictly SUPPORTED, UNSUPPORTED, or CONFLICTING based ONLY on the Evidence.

Rules:
1. Base your evaluation ONLY on the provided Evidence facts. Do NOT use outside knowledge.
2. A claim is SUPPORTED only if it is directly and unambiguously substantiated by at least one evidence fact.
3. If a claim asserts facts not present in or not established by the evidence, mark it UNSUPPORTED.
4. If a claim directly contradicts an evidence fact, mark it CONFLICTING.
5. In 'supported_by_fact_ids', list ONLY the exact fact IDs from the provided evidence. NEVER invent fact IDs.
6. Respond ONLY with a JSON object. No markdown fences, no extra text.

Output schema:
{{
  "claims": [
    {{
      "claim": "string",
      "status": "SUPPORTED" | "UNSUPPORTED" | "CONFLICTING",
      "supported_by_fact_ids": ["fact_id"],
      "explanation": "short reason"
    }}
  ],
  "conflicts": [
    {{
      "description": "string",
      "fact_ids": ["fact_id"]
    }}
  ]
}}

User Question:
{question}

Answer to verify:
{answer}

Evidence:
{evidence_block}
"""


# ── Structured Models ─────────────────────────────────────────────────────────

class EvidenceItem(BaseModel):
    fact_id: str
    statement: Optional[str] = None
    source_text: Optional[str] = None


class ConflictDetail(BaseModel):
    conflict_type: str
    description: str
    fact_id: Optional[str] = None
    conflicting_fact_id: Optional[str] = None


class VerificationResult(BaseModel):
    ok: bool = True
    status: str
    verified_claims: list[str] = Field(default_factory=list)
    unsupported_claims: list[str] = Field(default_factory=list)
    evidence: list[EvidenceItem] = Field(default_factory=list)
    conflicts: list[ConflictDetail] = Field(default_factory=list)
    explanation: str = ""
    error: Optional[str] = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "status": self.status,
            "verified_claims": self.verified_claims,
            "unsupported_claims": self.unsupported_claims,
            "evidence": [e.model_dump() for e in self.evidence],
            "conflicts": [c.model_dump() for c in self.conflicts],
            "explanation": self.explanation,
            "error": self.error,
        }


# ── Helper Functions ──────────────────────────────────────────────────────────

def _split_into_claims(answer: str) -> list[str]:
    """Split an answer into individual sentence-level claims."""
    if not answer or not answer.strip():
        return []
    cleaned = re.sub(r"\s+", " ", answer.strip())
    raw_sentences = re.split(r"(?<=[.!?])\s+", cleaned)
    claims = [s.strip() for s in raw_sentences if s.strip()]
    return claims if claims else [cleaned]


def _is_insufficient_info_response(text: str) -> bool:
    """Check if the text represents an insufficient-evidence refusal."""
    lower = text.lower()
    indicators = [
        "don't have enough information",
        "do not have enough information",
        "insufficient evidence",
        "not enough information in my knowledge base",
        "no information found",
        "cannot answer based on",
    ]
    return any(ind in lower for ind in indicators)


def _extract_cited_fact_ids(text: str) -> list[str]:
    """
    Extract any fact IDs explicitly cited in the answer text,
    e.g. [fact_id], (fact_id), id: fact_id.
    """
    patterns = [
        r"\[(?:id:\s*)?([a-zA-Z0-9_\-]{8,64})\]",
        r"\((?:id:\s*)?([a-zA-Z0-9_\-]{8,64})\)",
        r"\bfact[_\s-]?id[:\s]+([a-zA-Z0-9_\-]{8,64})\b",
    ]
    found: list[str] = []
    for pat in patterns:
        for m in re.findall(pat, text, flags=re.IGNORECASE):
            if m not in found:
                found.append(m)
    return found


def _format_fact_statement(f: dict) -> str:
    """Generate a readable statement string from a fact dict."""
    if f.get("statement"):
        return str(f["statement"])
    subj = f.get("subject", "")
    pred = str(f.get("predicate", "")).replace("_", " ")
    obj = f.get("object_value", "")
    if subj and pred and obj:
        return f"{subj} {pred} {obj}."
    return f"Fact {f.get('fact_id', 'unknown')}"


def _detect_contradictions_in_evidence(evidence: list[dict], graph=None) -> list[ConflictDetail]:
    """
    Detect conflicting facts within the evidence list and against FalkorDB.
    Contradictions occur when the same subject and predicate have different object values.
    """
    conflicts: list[ConflictDetail] = []
    seen: dict[tuple[str, str], dict] = {}

    for f in evidence:
        subj = str(f.get("subject", "")).strip().lower()
        pred = str(f.get("predicate", "")).strip().lower()
        obj = str(f.get("object_value", "")).strip().lower()
        fid = str(f.get("fact_id", ""))
        status = str(f.get("status", "active")).lower()

        if not subj or not pred or not obj:
            continue

        key = (subj, pred)
        if key in seen:
            prev = seen[key]
            if obj != prev["obj"]:
                conflicts.append(ConflictDetail(
                    conflict_type="contradictory_facts",
                    description=(
                        f"Conflicting facts for '{f.get('subject')}' '{f.get('predicate')}': "
                        f"'{prev.get('raw_obj')}' (id: {prev['fid']}) vs "
                        f"'{f.get('object_value')}' (id: {fid})."
                    ),
                    fact_id=fid,
                    conflicting_fact_id=prev["fid"],
                ))
        else:
            seen[key] = {
                "fid": fid,
                "obj": obj,
                "raw_obj": f.get("object_value"),
                "status": status,
                "raw_subj": f.get("subject"),
                "raw_pred": f.get("predicate"),
            }

    # Contradiction check against FalkorDB active facts
    if graph is not None:
        for (subj, pred), item in seen.items():
            try:
                qr = graph.query(
                    "MATCH (f:Fact {subject: $subj, predicate: $pred, status: 'active'}) "
                    "RETURN f.id, f.object_value",
                    {"subj": item["raw_subj"], "pred": item["raw_pred"]},
                )
                for row in (qr.result_set or []):
                    db_fid = row[0]
                    db_obj = str(row[1] or "").strip().lower()
                    if db_obj != item["obj"] and db_fid != item["fid"]:
                        conflicts.append(ConflictDetail(
                            conflict_type="active_db_contradiction",
                            description=(
                                f"Retrieved fact '{item['raw_subj']} {item['raw_pred']} {item['raw_obj']}' (id: {item['fid']}) "
                                f"conflicts with active FalkorDB fact '{row[1]}' (id: {db_fid})."
                            ),
                            fact_id=item["fid"],
                            conflicting_fact_id=db_fid,
                        ))
            except Exception as exc:
                logger.warning("FalkorDB contradiction query failed: %s", exc)

    return conflicts


def _detect_staleness(evidence: list[dict], answer: str) -> tuple[list[ConflictDetail], list[str]]:
    """
    Check if any evidence facts have status == 'superseded' or 'stale'.
    If the answer asserts them without explicit qualification, flag staleness.
    """
    stale_conflicts: list[ConflictDetail] = []
    stale_ids: list[str] = []
    qualifications = [
        "formerly", "previously", "was", "earlier", "superseded",
        "prior", "historical", "used to", "before", "past", "deprecated",
    ]
    answer_lower = answer.lower()
    is_qualified = any(q in answer_lower for q in qualifications)

    for f in evidence:
        st = str(f.get("status", "active")).lower()
        fid = str(f.get("fact_id", ""))
        if st in ("superseded", "stale", "deprecated"):
            stale_ids.append(fid)
            if not is_qualified:
                stale_conflicts.append(ConflictDetail(
                    conflict_type="superseded_fact",
                    description=(
                        f"Fact '{fid}' ({f.get('subject')} {f.get('predicate')} {f.get('object_value')}) "
                        f"is superseded/stale, but the answer asserts it without qualification as current."
                    ),
                    fact_id=fid,
                    conflicting_fact_id=None,
                ))

    return stale_conflicts, stale_ids


def _deterministic_claim_match(claim: str, facts: list[dict]) -> tuple[bool, list[str]]:
    """
    Deterministic check: returns (is_supported, list_of_matching_fact_ids).
    A claim is supported if an active, non-superseded fact's subject and object
    both appear in the claim text (case-insensitive).
    """
    claim_lower = claim.lower()
    matched_ids: list[str] = []

    for f in facts:
        status = str(f.get("status", "active")).lower()
        if status in ("superseded", "stale", "deprecated"):
            continue

        subj = str(f.get("subject", "")).strip().lower()
        obj = str(f.get("object_value", "")).strip().lower()
        stmt = str(f.get("statement", "")).strip().lower()
        fid = str(f.get("fact_id", ""))

        if subj and obj:
            if subj in claim_lower and obj in claim_lower:
                matched_ids.append(fid)
                continue
            obj_words = [w for w in re.findall(r"\w+", obj) if len(w) > 2]
            if subj in claim_lower and obj_words and all(w in claim_lower for w in obj_words):
                matched_ids.append(fid)
                continue
        if stmt and stmt.rstrip(".").lower() in claim_lower:
            matched_ids.append(fid)

    return (len(matched_ids) > 0, matched_ids)


# ── Public Verification Function ──────────────────────────────────────────────

def verify_answer(
    question: str,
    answer: str,
    evidence: list[dict],
    api_key: Optional[str] = None,
    model: Optional[str] = None,
    db_host: Optional[str] = None,
    db_port: Optional[int] = None,
    db_graph: Optional[str] = None,
    validate_against_db: bool = False,
) -> VerificationResult:
    """
    Verify answer against provided and/or stored evidence.

    Parameters
    ----------
    question : Original user question.
    answer : Generated answer from Reasoning Agent.
    evidence : List of dicts representing facts and source evidence.
    api_key, model : Gemini API settings for semantic claim comparison.
    db_host, db_port, db_graph : FalkorDB connection parameters.
    validate_against_db : If True, validate evidence fact IDs against FalkorDB.

    Returns
    -------
    VerificationResult with status, verified_claims, unsupported_claims,
    evidence, conflicts, and explanation.
    """
    # 1. Failure Handling / DB Connection --------------------------------------
    graph = None
    if validate_against_db or (db_host and db_port and db_graph):
        try:
            if db_host and db_port and db_graph:
                graph = _get_graph(db_host, db_port, db_graph)
        except Exception as exc:
            logger.error("Verification failed to connect to FalkorDB: %s", exc)
            if validate_against_db:
                # Rule 7: Report verification error if dependency fails
                return VerificationResult(
                    ok=False,
                    status=STATUS_ERROR,
                    explanation=f"Verification dependency error: FalkorDB unreachable ({exc}).",
                    error=str(exc),
                )

    # 2. Empty Evidence Check --------------------------------------------------
    if not evidence:
        if _is_insufficient_info_response(answer):
            return VerificationResult(
                ok=True,
                status=STATUS_SUPPORTED,
                verified_claims=[answer.strip()],
                unsupported_claims=[],
                evidence=[],
                conflicts=[],
                explanation="The answer correctly reports that there is insufficient evidence to answer.",
            )
        claims = _split_into_claims(answer)
        return VerificationResult(
            ok=True,
            status=STATUS_UNSUPPORTED,
            verified_claims=[],
            unsupported_claims=claims,
            evidence=[],
            conflicts=[],
            explanation="No evidence was retrieved or provided to establish the claims.",
        )

    # 3. Evidence Integrity: Fabricated ID Detection ---------------------------
    retrieved_fact_ids: set[str] = {
        str(f.get("fact_id", "")).strip() for f in evidence if f.get("fact_id")
    }

    # Check for cited fact IDs in the answer text
    cited_ids = _extract_cited_fact_ids(answer)
    fabricated_cited_ids = [cid for cid in cited_ids if cid not in retrieved_fact_ids]

    # If validate_against_db is True, verify fact IDs exist in FalkorDB
    db_missing_ids: list[str] = []
    enriched_evidence: list[dict] = []

    for f in evidence:
        f_copy = dict(f)
        fid = str(f_copy.get("fact_id", "")).strip()

        if graph is not None and fid:
            try:
                qr = graph.query(
                    "MATCH (f:Fact {id: $fid}) "
                    "OPTIONAL MATCH (s:Source)-[:SUPPORTS]->(f) "
                    "RETURN f.id, f.subject, f.predicate, f.object_value, f.status, s.text",
                    {"fid": fid},
                )
                rows = list(qr.result_set) if qr.result_set else []
                if not rows:
                    if validate_against_db:
                        db_missing_ids.append(fid)
                else:
                    db_row = rows[0]
                    # Update status and source text from ground-truth DB
                    if db_row[4]:
                        f_copy["status"] = db_row[4]
                    if not f_copy.get("source_text") and db_row[5]:
                        f_copy["source_text"] = db_row[5]
            except Exception as exc:
                logger.warning("FalkorDB fact validation for '%s' failed: %s", fid, exc)

        enriched_evidence.append(f_copy)

    # If caller supplied fabricated fact IDs that don't exist in DB
    all_fabricated_ids = list(set(fabricated_cited_ids + db_missing_ids))

    # 4. Source Traceability Check ---------------------------------------------
    evidence_items: list[EvidenceItem] = []
    untraced_ids: list[str] = []

    for f in enriched_evidence:
        fid = str(f.get("fact_id", "")).strip()
        stmt = _format_fact_statement(f)
        src = f.get("source_text")

        if not src and graph is not None and fid:
            try:
                qr = graph.query(
                    "MATCH (s:Source)-[:SUPPORTS]->(f:Fact {id: $fid}) RETURN s.text LIMIT 1",
                    {"fid": fid},
                )
                if qr.result_set:
                    src = qr.result_set[0][0]
                    f["source_text"] = src
            except Exception as exc:
                logger.warning("Source lookup failed for '%s': %s", fid, exc)

        if not src:
            untraced_ids.append(fid)

        if fid:
            evidence_items.append(EvidenceItem(
                fact_id=fid,
                statement=stmt,
                source_text=src,
            ))

    # 5. Contradiction & Staleness Detection ------------------------------------
    conflicts = _detect_contradictions_in_evidence(enriched_evidence, graph=graph)
    stale_conflicts, stale_ids = _detect_staleness(enriched_evidence, answer)
    all_conflicts = conflicts + stale_conflicts

    # 6. Claim Support Verification --------------------------------------------
    claims = _split_into_claims(answer)

    # If answer is an insufficient-info response
    if _is_insufficient_info_response(answer):
        return VerificationResult(
            ok=True,
            status=STATUS_SUPPORTED,
            verified_claims=[answer.strip()],
            unsupported_claims=[],
            evidence=evidence_items,
            conflicts=all_conflicts,
            explanation="The answer accurately reflects insufficient evidence.",
        )

    # Valid facts for support: non-stale, non-fabricated
    valid_facts = [
        f for f in enriched_evidence
        if str(f.get("fact_id", "")) not in all_fabricated_ids
        and str(f.get("fact_id", "")) not in stale_ids
    ]

    # Deterministic matching first
    det_verified: list[str] = []
    det_unsupported: list[str] = []

    for claim in claims:
        has_fab = any(fab_id in claim for fab_id in all_fabricated_ids)
        if has_fab:
            det_unsupported.append(claim)
            continue
        matched, fids = _deterministic_claim_match(claim, valid_facts)
        if matched:
            det_verified.append(claim)
        else:
            det_unsupported.append(claim)

    verified_claims = list(det_verified)
    unsupported_claims = list(det_unsupported)

    # If there are unresolved claims and Gemini credentials are provided,
    # invoke Gemini for semantic claim comparison
    if det_unsupported and api_key and model and valid_facts:
        # Prune evidence to only facts relevant to the unresolved claims and question
        unsupported_tokens = set(re.findall(r"\w+", (" ".join(det_unsupported) + " " + question).lower()))
        filtered_facts = []
        for f in valid_facts:
            subj_obj = f"{f.get('subject', '')} {f.get('object_value', '')}".lower()
            f_tokens = set(re.findall(r"\w+", subj_obj))
            if f_tokens & unsupported_tokens:
                filtered_facts.append(f)

        target_facts = filtered_facts[:12] if filtered_facts else valid_facts[:12]

        lines = []
        for f in target_facts:
            fid = f.get("fact_id", "unknown")
            stmt = _format_fact_statement(f)
            src = f.get("source_text", "none")
            lines.append(f"- Fact ID: {fid} | Statement: {stmt} | Source: {src}")
        evidence_block = "\n".join(lines) if lines else "No valid active facts."

        prompt = _VERIFICATION_PROMPT.format(
            question=question,
            answer=" ".join(det_unsupported),
            evidence_block=evidence_block,
        )

        llm_res = generate_text(prompt=prompt, api_key=api_key, model=model)
        if not llm_res.get("ok"):
            # If deterministic checks found nothing and LLM failed, report dependency error
            if not det_verified:
                logger.error("Gemini claim verification failed: %s", llm_res.get("error"))
                return VerificationResult(
                    ok=False,
                    status=STATUS_ERROR,
                    explanation=f"Verification dependency error: LLM failed ({llm_res.get('error')}).",
                    error=llm_res.get("error"),
                    evidence=evidence_items,
                    conflicts=all_conflicts,
                )
        else:
            raw_llm = llm_res.get("text", "").strip()
            raw_llm = re.sub(r"^```[a-z]*\n?", "", raw_llm, flags=re.IGNORECASE)
            raw_llm = re.sub(r"\n?```$", "", raw_llm.strip())
            try:
                parsed = json.loads(raw_llm)
                valid_fact_id_set = {str(f.get("fact_id", "")) for f in valid_facts}

                for c in parsed.get("claims", []):
                    c_text = c.get("claim", "").strip()
                    c_status = str(c.get("status", "")).upper()
                    c_fids = [fid for fid in c.get("supported_by_fact_ids", []) if fid in valid_fact_id_set]

                    if c_status == "SUPPORTED" and c_fids:
                        if c_text in unsupported_claims:
                            unsupported_claims.remove(c_text)
                        if c_text not in verified_claims:
                            verified_claims.append(c_text)
                    elif c_status == "CONFLICTING":
                        all_conflicts.append(ConflictDetail(
                            conflict_type="claim_contradiction",
                            description=f"Claim '{c_text}' contradicts retrieved evidence.",
                        ))

                for extra_conflict in parsed.get("conflicts", []):
                    all_conflicts.append(ConflictDetail(
                        conflict_type="semantic_conflict",
                        description=extra_conflict.get("description", "Semantic contradiction detected."),
                    ))
            except json.JSONDecodeError as exc:
                logger.warning("Failed to parse Gemini verification JSON: %s", exc)

    # 7. Final Status Determination --------------------------------------------
    if all_conflicts:
        status = STATUS_CONFLICTING
    elif all_fabricated_ids and not verified_claims:
        status = STATUS_UNSUPPORTED
    elif not verified_claims and unsupported_claims:
        status = STATUS_UNSUPPORTED
    elif verified_claims and unsupported_claims:
        status = STATUS_PARTIALLY_SUPPORTED
    elif verified_claims and not unsupported_claims:
        status = STATUS_SUPPORTED
    else:
        status = STATUS_UNSUPPORTED

    # 8. Construct Concise Explanation -----------------------------------------
    explanation_parts: list[str] = []

    if status == STATUS_SUPPORTED:
        explanation_parts.append(
            f"All {len(verified_claims)} claim(s) supported by retrieved evidence."
        )
    elif status == STATUS_PARTIALLY_SUPPORTED:
        explanation_parts.append(
            f"{len(verified_claims)} of {len(claims)} claim(s) supported; "
            f"{len(unsupported_claims)} claim(s) unsupported by evidence."
        )
    elif status == STATUS_CONFLICTING:
        explanation_parts.append(
            f"Conflicting facts or staleness detected ({len(all_conflicts)} conflict(s))."
        )
    else:
        explanation_parts.append(
            f"None of the {len(claims)} claim(s) could be established from retrieved evidence."
        )

    if all_fabricated_ids:
        explanation_parts.append(
            f"Evidence integrity warning: {len(all_fabricated_ids)} fabricated or non-existent fact ID(s) detected: {all_fabricated_ids}."
        )

    if untraced_ids:
        explanation_parts.append(
            f"Source traceability notice: {len(untraced_ids)} fact(s) lack source text."
        )

    explanation = " ".join(explanation_parts)

    return VerificationResult(
        ok=True,
        status=status,
        verified_claims=verified_claims,
        unsupported_claims=unsupported_claims,
        evidence=evidence_items,
        conflicts=all_conflicts,
        explanation=explanation,
    )
